import streamlit as st
import random
import re
from datetime import datetime

# 1. إعدادات واجهة التطبيق لتناسب شاشات الجوال والآيفون بشكل مثالي
st.set_page_config(
    page_title="مساعد أورا الذكي",
    page_icon="🤖",
    layout="centered"
)

# عنوان التطبيق الرئيسي
st.title("🤖 مساعد AuraAI الذكي")
st.markdown("مرحباً بك! أنا نظام ذكاء اصطناعي محلي ومصغر، يمكنك التحدث معي والدردشة باللغة العربية.")
st.write("---")

# 2. ذاكرة الشات لحفظ الرسائل ومنع اختفائها عند تحديث الشاشة (Session State)
if "messages" not in st.session_state:
    st.session_state.messages = [
        {"role": "assistant", "content": "أهلاً بك يا مبرمجنا العظيم! كيف يمكنني مساعدتك اليوم؟ 🧠"}
    ]

# 3. قاعدة البيانات المحلية للذكاء الاصطناعي (النوايا والردود الذكية)
قواعد_الذكاء = {
    r"(مرحبا|أهلا|اهلان|السلام|هلا|مرحب)": 
        "مرحباً بك! أنا AuraAI، العقل الذكي لنظام تشغيلك الخاص، كيف يمكنني إسنادك اليوم؟ 🤖",
    r"(من أنت|ماذا تفعل|من انت|وش وظيفتك)": 
        "أنا مساعد ذكاء اصطناعي محلي، جرى تصميمي لأعمل بكفاءة كاملة على الجوال لمساعدتك في معالجة الأوامر والدردشة الحية! 🧠",
    r"(كيف حالك|كيف الحرك|شخبارك|علومك)": 
        "أنا في قمة نشاطي البرمجي [100%] وأعمل بسلاسة تامة على معالج جوالك الخارق! شكراً لسؤالك اللطيف ⚡",
    r"(من صنعك|من طورك|مين سواك|من مبرمجك)": 
        "تم تصميمي وتطويري بالكامل بواسطة مبرمج عبقري ومكافح، يمتلك آيفون وهواوي قديم ويتحدى كل الصعاب التقنية ليتعلم البرمجة الحقيقية! 👑",
    r"(شكرا|تسلم|مشكور|يعطيك العافية)": 
        "العفو يا صديقي الغالي! هذا واجبي البرمجي دائماً وأنا في خدمتك 🌟",
    r"(الوقت|الساعة|التاريخ|اليوم)": 
        f"⏰ الوقت والتاريخ الحالي في نظامنا اللحظي هو: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}"
}

def توليد_رد_الذكاء(نص_المستخدم):
    """تحليل نص المستخدم والرد عليه ذكياً بناءً على الكلمات الدلالية"""
    نص_نظيف = نص_المستخدم.strip()
    
    # فحص العمليات الحسابية تلقائياً إذا طلب المستخدم حساب شيء بلغة البشر
    if any(كلمة_مفتاحية in نص_نظيف for كلمة_مفتاحية in ["احسب", "حساب", "كم"]):
        # استخراج الأرقام والرموز الرياضية فقط باستخدام الـ Regex لضمان الأمان
        المعادلة = re.sub(r"[^\d\+\-\*\/\(\)\.]", "", نص_نظيف)
        if المعادلة:
            try:
                الناتج = eval(المعادلة, {"__builtins__": None}, {})
                return f"📊 قمت بتحليل نصك وحساب العملية رياضياً بنجاح:\n\n🔢 ناتج الحساب لـ ({المعادلة}) = **{الناتج}**"
            except:
                pass

    # فحص الكلمات الدلالية لمطابقة نية المستخدم في الدردشة
    for النمط, الرد in قواعد_الذكاء.items():
        if re.search(النمط, نص_نظيف):
            return الرد

    # ردود بديلة عشوائية وذكية في حال لم يتم مطابقة العبارة بدقة
    الردود_الافتراضية = [
        "لم أفهم العبارة بدقة لأنني مفسر محلي مصغر، ولكن يمكنك أن تطلب مني (احسب 100*2) أو الدردشة معي! 💡",
        "تعبيرك ذكي جداً! ولكن قواعدي المحلية تحتاج كلمات أبسط، جرب قول: 'من أنت' أو 'من صنعك' 🤖",
        "كودك يشتغل بكفاءة في الخلفية! هل تريد مني حساب عملية رياضية؟ اكتب مثلاً 'احسب 50+50' 📊"
    ]
    return random.choice(الردود_الافتراضية)

# 4. عرض رسائل الشات السابقة بشكل مرئي ومنسق على شاشة الجوال
for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.write(message["content"])

# 5. استقبال مدخلات المستخدم الحية من صندوق الشات التفاعلي أسفل الشاشة
if user_input := st.chat_input("اكتب رسالتك هنا للتحدث مع الذكاء الاصطناعي..."):
    # عرض رسالة المستخدم فوراً على واجهة التطبيق
    with st.chat_message("user"):
        st.write(user_input)
    st.session_state.messages.append({"role": "user", "content": user_input})
    
    # توليد رد البوت الذكي وعرضه مع تأثير "جاري التفكير..." الحركي
    with st.chat_message("assistant"):
        with st.spinner("جاري تفكير وتحليل النوايا..."):
            bot_reply = توليد_رد_الذكاء(user_input)
            st.write(bot_reply)
    st.session_state.messages.append({"role": "assistant", "content": bot_reply})
